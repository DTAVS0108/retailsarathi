  String get locale => _locale;
  bool get isHindi => _locale == 'hi';

  Future<void> bootstrap() async {
    final prefs = await SharedPreferences.getInstance();
    _locale = prefs.getString(prefKey) ?? 'en';
    notifyListeners();
  }

  Future<void> setLocale(String code) async {
    if (code != 'en' && code != 'hi') return;
    _locale = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(prefKey, code);
    notifyListeners();
  }

  Future<void> toggle() => setLocale(isHindi ? 'en' : 'hi');

  String t(String key) {
    final map = isHindi ? _hi : _en;
    return map[key] ?? _en[key] ?? key;
  }

