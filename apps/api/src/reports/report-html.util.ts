import { escapeHtml, fmtInr } from './report-export.util';

export type StatementColumn = { key: string; label: string; align?: 'left' | 'right' };

export function buildReportHtml(opts: {
  title: string;
  subtitle?: string;
  shopName?: string;
  shopMeta?: string;
  partyName?: string;
  partyMeta?: string;
  periodLabel: string;
  summary?: Array<{ label: string; value: string }>;
  columns: StatementColumn[];
  rows: Array<Record<string, unknown>>;
  footerNote?: string;
}): string {
  const summaryHtml = (opts.summary ?? [])
    .map(
      (s) =>
        `<div class="stat"><div class="stat-label">${escapeHtml(s.label)}</div><div class="stat-value">${escapeHtml(s.value)}</div></div>`,
    )
    .join('');

  const head = opts.columns
    .map((c) => `<th class="${c.align === 'right' ? 'num' : ''}">${escapeHtml(c.label)}</th>`)
    .join('');

  const body = opts.rows
    .map((row) => {
      const cells = opts.columns
        .map((c) => {
          const raw = row[c.key];
          const text =
            typeof raw === 'number' &&
            (c.key.toLowerCase().includes('amount') ||
              c.key.toLowerCase().includes('total') ||
              c.key.toLowerCase().includes('tax') ||
              c.key.toLowerCase().includes('balance') ||
              c.key.toLowerCase().includes('paid') ||
              c.key.toLowerCase().includes('debit') ||
              c.key.toLowerCase().includes('credit'))
              ? fmtInr(raw)
              : String(raw ?? '');
          return `<td class="${c.align === 'right' ? 'num' : ''}">${escapeHtml(text)}</td>`;
        })
        .join('');
      return `<tr>${cells}</tr>`;
    })
    .join('');

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<title>${escapeHtml(opts.title)}</title>
<style>
  @page { size: A4; margin: 12mm; }
  body { font-family: "Segoe UI", Arial, sans-serif; color: #111; font-size: 12px; margin: 0; padding: 16px; }
  .brand { font-size: 20px; font-weight: 700; color: #0f766e; margin: 0 0 2px; }
  h1 { font-size: 18px; margin: 8px 0 4px; }
  .meta { color: #555; margin-bottom: 12px; }
  .stats { display: flex; flex-wrap: wrap; gap: 10px; margin: 12px 0 16px; }
  .stat { border: 1px solid #ddd; border-radius: 6px; padding: 8px 10px; min-width: 120px; }
  .stat-label { font-size: 10px; color: #666; text-transform: uppercase; }
  .stat-value { font-weight: 600; margin-top: 2px; }
  table { width: 100%; border-collapse: collapse; }
  th, td { border-bottom: 1px solid #e5e5e5; padding: 6px 4px; text-align: left; vertical-align: top; }
  th { font-size: 10px; text-transform: uppercase; color: #555; }
  td.num, th.num { text-align: right; white-space: nowrap; }
  .footer { margin-top: 16px; color: #777; font-size: 10px; }
  @media print { .no-print { display: none; } }
</style>
</head>
<body>
  <button class="no-print" onclick="window.print()" style="margin-bottom:12px;padding:6px 10px;">Print / Save PDF</button>
  ${opts.shopName ? `<div class="brand">${escapeHtml(opts.shopName)}</div>` : ''}
  ${opts.shopMeta ? `<div class="meta">${escapeHtml(opts.shopMeta)}</div>` : ''}
  <h1>${escapeHtml(opts.title)}</h1>
  <div class="meta">
    ${opts.partyName ? `<div><strong>${escapeHtml(opts.partyName)}</strong>${opts.partyMeta ? ` · ${escapeHtml(opts.partyMeta)}` : ''}</div>` : ''}
    <div>Period: ${escapeHtml(opts.periodLabel)}</div>
  </div>
  ${summaryHtml ? `<div class="stats">${summaryHtml}</div>` : ''}
  <table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>
  <div class="footer">${escapeHtml(opts.footerNote || 'Generated by RetailSarathi · Print this page to save PDF')}</div>
</body>
</html>`;
}

export function buildPaymentReceiptHtml(opts: {
  shopName?: string;
  shopMeta?: string;
  title: string;
  partyName: string;
  partyMeta?: string;
  paymentDate: string;
  method: string;
  reference?: string;
  status: string;
  amount: number;
  tdsAmount?: number;
  advanceAmount?: number;
  notes?: string;
  allocations: Array<{ docNo: string; amount: number }>;
}): string {
  const allocRows = opts.allocations
    .map(
      (a) =>
        `<tr><td>${escapeHtml(a.docNo)}</td><td class="num">${escapeHtml(fmtInr(a.amount))}</td></tr>`,
    )
    .join('');
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/><title>${escapeHtml(opts.title)}</title>
<style>
@page{size:A5;margin:10mm} body{font-family:"Segoe UI",Arial,sans-serif;font-size:12px;padding:16px}
.brand{font-size:18px;font-weight:700;color:#0f766e} h1{font-size:16px;margin:8px 0}
.meta{color:#555} table{width:100%;border-collapse:collapse;margin-top:12px}
th,td{border-bottom:1px solid #e5e5e5;padding:6px 4px;text-align:left}
td.num,th.num{text-align:right} .amt{font-size:22px;font-weight:700;margin:10px 0}
@media print{.no-print{display:none}}
</style></head><body>
<button class="no-print" onclick="window.print()">Print / Save PDF</button>
${opts.shopName ? `<div class="brand">${escapeHtml(opts.shopName)}</div>` : ''}
${opts.shopMeta ? `<div class="meta">${escapeHtml(opts.shopMeta)}</div>` : ''}
<h1>${escapeHtml(opts.title)}</h1>
<div class="meta"><strong>${escapeHtml(opts.partyName)}</strong>${opts.partyMeta ? ` · ${escapeHtml(opts.partyMeta)}` : ''}</div>
<div class="meta">${escapeHtml(opts.paymentDate)} · ${escapeHtml(opts.method)} · ${escapeHtml(opts.status)}${opts.reference ? ` · Ref ${escapeHtml(opts.reference)}` : ''}</div>
<div class="amt">${escapeHtml(fmtInr(opts.amount))}</div>
${opts.tdsAmount ? `<div class="meta">TDS: ${escapeHtml(fmtInr(opts.tdsAmount))}</div>` : ''}
${opts.advanceAmount ? `<div class="meta">Advance held: ${escapeHtml(fmtInr(opts.advanceAmount))}</div>` : ''}
${opts.notes ? `<div class="meta">${escapeHtml(opts.notes)}</div>` : ''}
<table><thead><tr><th>Allocated to</th><th class="num">Amount</th></tr></thead>
<tbody>${allocRows || '<tr><td colspan="2">No bill allocations</td></tr>'}</tbody></table>
<div class="meta" style="margin-top:16px;font-size:10px">Generated by RetailSarathi · Print to save PDF</div>
</body></html>`;
}
